#include <bits/stdc++.h>        // 包含所有常用头文件（竞赛常用写法）
using namespace std;

int main() {
    ios::sync_with_stdio(false); // 关闭 cin/cout 与 stdio 的同步，加速输入输出
    cin.tie(nullptr);            // 解除 cin 与 cout 的绑定，加速

    int N;
    cin >> N;                    // 输入方格大小 N（N×N）

    // 建立一个 (N+1)*(N+1) 的二维数组 a，用来存储每个格子的数值（1-based）
    vector<vector<int>> a(N + 1, vector<int>(N + 1, 0));

    // 读取数据，直到出现 "0 0 0" 表示输入结束
    while (true) {
        int x, y, v;
        cin >> x >> y >> v;
        if (x == 0 && y == 0 && v == 0) break; // 结束输入
        a[x][y] = v;                           // 在 (x,y) 位置放入数字 v
    }

    const int NEG = -1e9; // 定义一个很小的负数，表示不可达状态

    // dp[x1][x2] 表示在当前步（由外层循环 t 决定）时，
    // 两个人分别在第 x1、x2 行时（列由 t - x1、t - x2 决定）能取得的最大和。
    vector<vector<int>> dp(N + 1, vector<int>(N + 1, NEG));

    dp[1][1] = a[1][1]; // 初始状态：两人都在 (1,1)，取到 a[1][1] 这一个格子的值

    // 枚举步数和 t = x + y（两人同步走）
    // 起点 (1,1) 对应 t=2，已初始化好，因此从 t=3 开始

    //ndp代表的新一层的 dp 表
    for (int t = 3; t <= 2 * N; ++t) {
        // 新一层的 ndp 表，全部初始化为 NEG（不可达）
        vector<vector<int>> ndp(N + 1, vector<int>(N + 1, NEG));

        // 对于给定 t，x 的范围受限：x + y = t => y = t - x 必须在 [1, N]
        int xmin = max(1, t - N);
        int xmax = min(N, t - 1);

        // 遍历第一个人的行号 x1
        for (int x1 = xmin; x1 <= xmax; ++x1) {
            int y1 = t - x1;           // 第一个人的列坐标
            if (y1 < 1 || y1 > N) continue; // 越界则跳过

            // 遍历第二个人的行号 x2
            for (int x2 = xmin; x2 <= xmax; ++x2) {
                int y2 = t - x2;           // 第二个人的列坐标
                if (y2 < 1 || y2 > N) continue; // 越界则跳过

                int best = NEG; // 当前状态的最优前驱值

                // 四种转移方式（两人都向下/右的组合）：
                // 1. 两人都从上方来
                if (x1 - 1 >= 1 && x2 - 1 >= 1)
                    best = max(best, dp[x1 - 1][x2 - 1]);
                // 2. 第1人从上方来，第2人从左方来
                if (x1 - 1 >= 1 && y2 - 1 >= 1)
                    best = max(best, dp[x1 - 1][x2]);
                // 3. 第1人从左方来，第2人从上方来
                if (y1 - 1 >= 1 && x2 - 1 >= 1)
                    best = max(best, dp[x1][x2 - 1]);
                // 4. 两人都从左方来
                if (y1 - 1 >= 1 && y2 - 1 >= 1)
                    best = max(best, dp[x1][x2]);

                // 如果没有合法前驱状态，则跳过
                if (best == NEG) continue;

                // 当前两个格子增加的值：
                int add = 0;
                if (x1 == x2 && y1 == y2)
                    add = a[x1][y1]; // 两人站在同一个格子，只加一次
                else
                    add = a[x1][y1] + a[x2][y2]; // 否则两格都加上

                // 更新当前层的 ndp
                ndp[x1][x2] = max(ndp[x1][x2], best + add);
            }
        }

        // 将新一层结果赋值给 dp，准备下一步
        //std::vector::swap() 会直接交换两个 vector 的内容，不复制数据，速度非常快。
        //dp 和 ndp 互换指针；
        //原来的 ndp（新的一层）变成“旧的一层”；
        //原来的 dp（旧的一层）可以被复用，下一轮再写入。
        dp.swap(ndp);
    }

    // 答案是两人都到达 (N,N) 时的最大和
    int ans = dp[N][N];

    // 防止出现负数情况（理论上不会）
    if (ans < 0) ans = 0;

    cout << ans << "\n"; // 输出结果
    return 0;
}
/*
额外说明与常见疑点

1. 为什么把“走两次”变成“两个人同步走”？
这是该题的经典 trick：把两次从左上到右下的路径合并为两个人同时走，
每一步两人都向右或向下一步。这样能够把「路径交叠只计一次」
通过判断 (x1,y1)==(x2,y2) 直接处理，并把问题转成三维 DP（或二维按步压缩的 DP）。

2. 复杂度
外层 t 有 O(N)（确切是 2N-2 层）。
每层枚举 x1、x2 各 O(N)，所以总体时间复杂度 O(N^3)。
当 N <= 9 时非常快。空间复杂度 O(N^2)（dp 矩阵）。

3. 为什么 t 从 3 开始？

t = x+y。起始在 (1,1)，t=2 我们已经以 dp[1][1] = a[1][1] 初始化好了；
所以从下一步 t=3 开始做转移。也可以把循环从 t=2 开但代码需要对应调整初始与前驱检查。

4. 边界检查为何复杂？

在判断四种前驱时用到了 x1-1 >= 1、y1-1 >= 1 等，
因为你不能从不存在的状态转移（例如 x1-1==0 表示上一层不在合法行）。
这些判断确保我们只读取 dp 中合法位置。
5. 为何使用 NEG=-1e9 而不是 INT_MIN？

为了避免 INT_MIN + something 导致溢出或不可预测行为，
用一个较小但不极端的负数更安全；同时题目中合法和不会接近 -1e9。

6. 为什么 dp[N][N] 总能到？
两个人只向右或向下走，从 (1,1) 到 (N,N) 必然存在路径（组合数多），
所以在正确的转移实现下最后一层 t=2N 的 dp[N][N] 应该有值（除非输入非法）。

7. 若两路径能重叠且都取走同格，
如果第一次取走了，第二次就不能再取 — 这个实现是如何保证的？

在“同步走”模型里，若两个人在同一格并且都“经过”它（即两条路径交叠），
我们只在那一步把该格的值加一次（if(x1==x2 && y1==y2) add = a[x1][y1];），
因此不会重复计数；如果两个人在不同步的时间分别经过同一格，
这种情形在原问题里也等同于两个路径都取了同格（但题目要求第二次取时格子已经为 0），
但用同步模型枚举两条完整路径的组合可以覆盖这种情况且只计一次 
—— 这是经典等价转换的核心（详见竞赛题解）。
*/